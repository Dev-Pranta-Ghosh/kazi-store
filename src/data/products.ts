interface PInput {
  name: string;
  brand: string;
  category: string;
  subcategory: string;
  price: number;
  originalPrice?: number;
  rating: number;
  reviewCount: number;
  pool: number[];
  imgA: number;
  imgB: number;
  description: string;
  benefits: string[];
  ingredients: string;
  howToUse: string;
  stock: number;
  tags: string[];
  concerns?: string[];
  isNew?: boolean;
  isBestSeller?: boolean;
  createdAt: string;
}

let counter = 0;
function p(input: PInput): Product {
  counter += 1;
  const { pool, imgA, imgB, ...rest } = input;
  return {
    id: `p${String(counter).padStart(3, "0")}`,
    slug: input.name
      .toLowerCase()
      .replace(/[^a-z0-9\s-]/g, "")
      .trim()
      .replace(/[\s_]+/g, "-")
      .replace(/-+/g, "-")
      .slice(0, 60),
    originalPrice: input.originalPrice ?? input.price,
    concerns: input.concerns ?? [],
    images: [img(pool[imgA]), img(pool[imgB]), img(pool[imgA], 900, 1200), img(pool[imgB], 900, 1200)],
    ...rest,
  };
}

