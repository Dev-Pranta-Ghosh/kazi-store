export const BRANDS: string[] = Array.from(new Set(PRODUCTS.map((pr) => pr.brand))).sort();

export const CONCERNS: string[] = [
  "Acne Care",
  "Hydration",
  "Brightening",
  "Sensitive Skin",
  "Sun Protection",
  "Anti-Aging",
];

export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((pr) => pr.slug === slug);
}

export function getProductsByCategory(slug: string): Product[] {
  return PRODUCTS.filter((pr) => pr.category === slug);
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return CATEGORIES.find((c) => c.slug === slug);
}

export function relatedProducts(product: Product, limit = 8): Product[] {
  const sameCat = PRODUCTS.filter(
    (pr) => pr.id !== product.id && pr.category === product.category
  );
  const sameBrand = PRODUCTS.filter(
    (pr) =>
      pr.id !== product.id &&
      pr.brand === product.brand &&
      pr.category !== product.category
  );
  return [...sameCat, ...sameBrand].slice(0, limit);
}

export function searchProducts(query: string): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return PRODUCTS.filter((p) => {
    const hay = [
      p.name,
      p.brand,
      p.subcategory,
      p.category.replace(/-/g, " "),
      ...p.tags,
      ...p.concerns,
    ]
      .join(" ")
      .toLowerCase();
    return q.split(/\s+/).every((token) => hay.includes(token));
  });
}

export type SortKey =
  | "newest"
  | "popular"
  | "rating"
  | "price-asc"
  | "price-desc";

export function sortProducts(list: Product[], sort: SortKey): Product[] {
  const arr = [...list];
  switch (sort) {
    case "price-asc":
      return arr.sort((a, b) => a.price - b.price);
    case "price-desc":
      return arr.sort((a, b) => b.price - a.price);
    case "rating":
      return arr.sort((a, b) => b.rating - a.rating || b.reviewCount - a.reviewCount);
    case "popular":
      return arr.sort((a, b) => b.reviewCount - a.reviewCount);
    case "newest":
    default:
      return arr.sort((a, b) => +new Date(b.createdAt) - +new Date(a.createdAt));
  }
}
